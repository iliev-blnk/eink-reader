#!/usr/bin/env python3
"""Rasterize a TTF/OTF into a 1-bit bitmap font for the e-reader firmware.

v0: writes a C source file (font_t + glyph table + bitmaps) for fonts that are
compiled into the firmware, e.g. the UI/debug font. The binary on-SD font
format (spec/font-format.md) comes later and will reuse the same rasterizer.

    fonttool.py --ttf /usr/share/fonts/noto/NotoSans-Regular.ttf --size 16 \
        --name font_ui16 --out ../../firmware/components/core/fonts/font_ui16.c

Glyph bitmaps are hinted and rendered without antialiasing (FreeType via
Pillow, fontmode "1"). Rows are padded to whole bytes, MSB first, 1 = ink.
"""
import argparse
import sys

from PIL import Image, ImageDraw, ImageFont

# Latin basic + Latin-1 + Latin Extended-A (ă â î ş ţ ...), Romanian comma-below
# ș ț (U+0218–U+021B), Cyrillic (Russian + Ukrainian), typographic punctuation.
DEFAULT_RANGES = (
    "0x20-0x7E,0xA0-0xFF,0x100-0x17F,0x218-0x21B,0x400-0x45F,"
    "0x2010-0x2014,0x2018-0x201E,0x2022,0x2026,0x2039-0x203A,0x20AC,0xFFFD"
)


def parse_ranges(spec):
    cps = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        lo, _, hi = part.partition("-")
        lo = int(lo, 0)
        hi = int(hi, 0) if hi else lo
        cps.update(range(lo, hi + 1))
    return sorted(cps)


def render(font, ch):
    """Return (bitmap rows as list of bytes objects, w, h, x_off, y_off, advance)."""
    advance = round(font.getlength(ch))
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return [], 0, 0, 0, 0, advance
    img = Image.new("1", (w, h), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((-x0, -y0), ch, font=font, fill=1, anchor="ls")
    # Trim empty borders left by the bbox estimate.
    box = img.getbbox()
    if box is None:
        return [], 0, 0, 0, 0, advance
    img = img.crop(box)
    x0 += box[0]
    y0 += box[1]
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if px[x, y]:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return rows, w, h, x0, y0, advance


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True, help="pixel size (FreeType em size)")
    ap.add_argument("--name", required=True, help="C symbol name, e.g. font_ui16")
    ap.add_argument("--ranges", default=DEFAULT_RANGES)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    ascent, descent = font.getmetrics()
    notdef = render(font, chr(0x10FFFD))[0]  # a codepoint no font has

    glyphs, data, missing = [], bytearray(), []
    for cp in parse_ranges(args.ranges):
        rows, w, h, xo, yo, adv = render(font, chr(cp))
        if rows and rows == notdef and cp != 0xFFFD:
            missing.append(cp)
            continue
        if not (-128 <= xo <= 127 and -128 <= yo <= 127 and w < 256 and h < 256 and adv < 256):
            sys.exit(f"glyph U+{cp:04X} out of range for the glyph record")
        glyphs.append((cp, len(data), w, h, xo, yo, adv))
        for r in rows:
            data += r

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(f"// Generated by tools/fonttool/fonttool.py, do not edit.\n")
        f.write(f"// Source: {args.ttf.rsplit('/', 1)[-1]} at {args.size} px (SIL Open Font License).\n")
        f.write(f"// {len(glyphs)} glyphs, {len(data)} bytes of bitmaps.\n\n")
        f.write('#include "font.h"\n\n')
        f.write(f"static const uint8_t bitmaps[{max(len(data), 1)}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"static const font_glyph_t glyphs[{len(glyphs)}] = {{\n")
        for cp, off, w, h, xo, yo, adv in glyphs:
            f.write(f"    {{0x{cp:04x}, {off}, {w}, {h}, {xo}, {yo}, {adv}}},\n")
        f.write("};\n\n")
        f.write(f"const font_t {args.name} = {{\n")
        f.write(f'    .name = "{args.name}",\n')
        f.write(f"    .ascent = {ascent},\n")
        f.write(f"    .descent = {descent},\n")
        f.write(f"    .line_height = {ascent + descent},\n")
        f.write(f"    .glyph_count = {len(glyphs)},\n")
        f.write("    .glyphs = glyphs,\n")
        f.write("    .bitmaps = bitmaps,\n")
        f.write("};\n")

    print(f"{args.name}: {len(glyphs)} glyphs, {len(data)} B bitmaps, ascent {ascent}, descent {descent}")
    if missing:
        print("missing in font: " + " ".join(f"U+{cp:04X}" for cp in missing))


if __name__ == "__main__":
    main()
